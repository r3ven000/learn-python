   
# === Записная книжка путешественника ===

# 1. КОРТЕЖ (tuple) - неизменяемые данные. Используем круглые скобки.
# Координаты нашего старта (широта, долгота)
home_coordinates = (55.75, 37.61)

# 2. МНОЖЕСТВО (set) - только уникальные значения. Используем фигурные скобки.
# Страны, в которых мы уже побывали
visited_countries = {"Россия", "Беларусь"}

# 3. СПИСОК (list) - упорядоченная коллекция, которую можно менять. Используем квадратные скобки.
# История наших перемещений
travel_log = ["Вышли из дома", "Прибыли в аэропорт"]

# 4. СЛОВАРЬ (dict) - пары "ключ: значение". Используем фигурные скобки и двоеточие.
# Ключ - название города, Значение - его население (в миллионах)
cities_population = {
    "Москва": 13.0,
    "Минск": 1.9
}

print("--- Добро пожаловать в Записную книжку путешественника ---")
print("Наши стартовые координаты:", home_coordinates)

# Используем бесконечный цикл для создания простого меню
while True:
    print("\nЧто вы хотите сделать?")
    print("1 - Добавить новую страну (Множество)")
    print("2 - Добавить запись в историю (Список)")
    print("3 - Посмотреть население города (Словарь)")
    print("0 - Выйти из программы")
    
    # Получаем данные от пользователя
    choice = input("Введите номер действия: ")
    
    if choice == "1":
        country = input("Какую страну вы посетили? ")
        # Метод .add() добавляет элемент во множество
        visited_countries.add(country) 
        print("Обновленный список уникальных стран:", visited_countries)
        
    elif choice == "2":
        action = input("Что произошло? ")
        # Метод .append() добавляет элемент в конец списка
        travel_log.append(action) 
        print("История путешествий:", travel_log)
        
    elif choice == "3":
        city = input("Введите название города (Москва или Минск): ")
        # Читаем значение из словаря по ключу с помощью метода .get()
        # Если города нет в словаре, он безопасно вернет текст "Город не найден"
        population = cities_population.get(city, "Город не найден")
        print("Население:", population)
        
    elif choice == "0":
        print("Завершение программы. До встречи!")
        break # Команда break останавливает наш цикл
        
    else:
        print("Неизвестная команда, попробуйте еще раз.")


